def flat_part_view(c, part, ox, oy, s, show_bends=True):
    poly(c, [(ox + x * s, oy + y * s) for x, y in part.outline], INK, STEEL_LIGHT, 0.85)
    for cut in part.cuts_polys():
        poly(c, [(ox + x * s, oy + y * s) for x, y in cut], INK, white, 0.45)
    if show_bends:
        for b in part.bends:
            col = Color(0.15, 0.40, 0.72) if b.get('ang', 90) == 0 else ACC
            dsh = [4, 2] if b.get('ang', 90) == 0 else [7, 2, 1.5, 2]
            line(c, (ox + b['p1'][0] * s, oy + b['p1'][1] * s),
                 (ox + b['p2'][0] * s, oy + b['p2'][1] * s), 0.55, col, dash=dsh)


def rfront_plan_pts(ox, oy, w, d, r):
    """Контур в плане 900 × D со скруглёнными передними углами R80 (фронт снизу на y=oy)."""
    pts = [(ox + r, oy), (ox + w - r, oy)]
    for i in range(1, 9):
        a = math.radians(-90 + 90 * i / 8.0)
        pts.append((ox + w - r + r * math.cos(a), oy + r + r * math.sin(a)))
    pts += [(ox + w, oy + d), (ox, oy + d)]
    for i in range(9):
        a = math.radians(180 + 90 * i / 8.0)
        pts.append((ox + r + r * math.cos(a), oy + r + r * math.sin(a)))
    return pts


