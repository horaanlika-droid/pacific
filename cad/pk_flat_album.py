def iso(c, rect, explode=0.0, lw=0.5, bbox_items=None):
    return draw_iso(c, station_items(explode), rect, lw=lw, pad=8.0,
                    bbox_items=bbox_items or station_items(explode))


def iso_lab(c, ret, p3, text, dx=0.0, dy=0.0, align='l'):
    ox, oy, k = ret
    u, v = _p3(p3)
    txt(c, ox + u * k + dx, oy + v * k + dy, text, 6.8, color=GREY, align=align)


