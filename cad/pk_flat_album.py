def side_view(c, ox, oy, k):
    """Боковое сечение станции: слои боковины и горизонтальные плиты."""
    def P(y, z):
        return (ox + y * k, oy + z * k)

    prof = [(0, 0), (600, 0), (600, F.LOW_TOP), (140, F.LOW_TOP), (140, F.H),
            (0, F.H)]
    poly(c, [P(*q) for q in prof], INK, Color(.955, .955, .945), 0.9)
    # горизонтальные плиты — толстые линии
    def plate(y0, y1, z, code, side='r', color=INK, lw=2.4):
        line(c, P(y0, z), P(y1, z), lw, color)
        mx, my = P((y0 + y1) / 2.0, z)
        txt(c, mx, my + 5, code, 6.4, align='c', color=color)

