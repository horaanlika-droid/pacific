def station_items(explode=0.0):
    e = explode
    it = []

    def add(code, box, off=(0, 0, 0), **kw):
        it.append(dict(code=code, box=box, off=off, **kw))

    T = F.T
    # левая / правая боковины — одинаковые полосы
    for sx, dx in ((0.0, -1), (F.W - T, +1)):
        add('F1', (sx, sx + T, 0, 600, 0, 20), (dx * 260 * e, 0, 0),
            fill=Color(.83, .84, .83))
        add('F2', (sx, sx + T, 0, 600, F.LOW_BOT, F.LOW_TOP), (dx * 260 * e, 0, 0),
            fill=Color(.86, .87, .86))
        add('F3', (sx, sx + T, 0, 140, F.WORK_Z1, F.TOWER_Z1), (dx * 260 * e, 0, 0),
            fill=Color(.88, .89, .88))
        add('F4', (sx, sx + T, 0, 140, F.DRIP_Z1, F.LEDGE_Z0), (dx * 260 * e, 0, 0),
            fill=Color(.90, .90, .89))
    add('F5', (0, F.W, 0, 600, F.BOT_Z0, F.BOT_Z1), (0, 0, -230 * e),
        fill_side=Color(.80, .81, .80))
    add('F6', (0, F.W, F.FRONT_Y0, 600, F.WORK_Z0, F.WORK_Z1), (0, 0, +260 * e),
        fill_side=Color(.80, .81, .80),
        holes=[(g['x'], g['y'], g['w'], g['h'], g['r']) for g in F.GNS] +
              [(F.SINK['x'], F.SINK['y'], F.SINK['w'], F.SINK['h'], F.SINK['r'])])
    add('F7', (0, F.W, 0, 140, F.DRIP_Z0, F.DRIP_Z1), (0, -40 * e, +380 * e),
        fill_side=Color(.80, .81, .80))
    add('F8', (T, F.W - T, F.FRONT_Y0, F.FRONT_Y1, F.DRIP_Z1, F.LEDGE_Z0),
        (0, -300 * e, +120 * e))
