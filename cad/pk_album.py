def station(explode=0.0, perf=True):
    e = explode
    it = []
    add = lambda code, box, off=(0, 0, 0), **kw: it.append(
        dict(code=code, box=box, off=off, **kw))
    add('E1', (0, 1.5, 1.2, 600, 0, 1020), (-230 * e, 0, 0),
        step=(140, 820), show_step_top=(e > 0), fill_side=Color(.80, .81, .80))
    add('E2', (898.5, 900, 1.2, 600, 0, 1020), (230 * e, 0, 0),
        step=(140, 820), show_step_top=(e > 0))
    add('E3', (0, 900, 0, 1.2, 12, 346), (0, -150 * e, -430 * e))
    add('E4', (0, 900, 0, 1.2, 349, 683), (0, -150 * e, -430 * e))
    add('E5', (0, 900, 0, 1.2, 686, 1020), (0, -150 * e, -430 * e))
    ty = G.TOPY
    e7_holes = [(g['x'], g['y'] + ty, g['w'], g['h'], g['r']) for g in G.CUT_GNS]
    e7_holes += [(s['x'], s['y'] + ty, s['w'], s['h'], s['r']) for s in G.CUT_SINKS]
    add('E7', (0, 900, 140, 600, 820, 850), (0, 0, 400 * e), holes=e7_holes)
