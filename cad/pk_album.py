def flat_view(c, part, ox, oy, s, bends=True, fill=FILL_FRONT, lw=0.9):
    poly(c, [(ox + x * s, oy + y * s) for x, y in part.outline], INK, fill, lw)
    for cut in part.cuts_polys():
        poly(c, [(ox + x * s, oy + y * s) for x, y in cut], INK, white, 0.5)
    for hook in (getattr(part, 'hooks', []) or []):
        poly(c, [(ox + x * s, oy + y * s) for x, y in hook], ACC, None, 0.9, close=False)
    for tab in (getattr(part, 'tabs', []) or []):
        poly(c, [(ox + x * s, oy + y * s) for x, y in tab], ACC, None, 0.9, close=True)
    if bends:
        for b in part.bends:
            line(c, (ox + b['p1'][0] * s, oy + b['p1'][1] * s),
                 (ox + b['p2'][0] * s, oy + b['p2'][1] * s), 0.5, ACC,
                 dash=[7, 2, 1.4, 2])


def plate(c, x, y, w, h, fill=FILL_FRONT, lw=1.0):
    poly(c, [(x, y), (x + w, y), (x + w, y + h), (x, y + h)], INK, fill, lw)


def hatch_rect(c, x, y, w, h, step=3.2):
    c.saveState()
    p = c.beginPath()
    p.rect(x, y, w, h)
    c.clipPath(p, stroke=0, fill=0)
    c.setLineWidth(0.35)
    c.setStrokeColor(HATCH)
    n = int((w + h) / step) + 2
    for i in range(n):
        c.line(x - h + i * step, y, x + i * step, y + h)
    c.restoreState()


def sec_bar(c, x, y, w, h, fill=Color(.86, .87, .86), minw=1.6, minh=1.6):
    """сечение: толщина листа на чертеже не менее 1,6 pt — иначе не читается"""
    w, h = max(w, minw), max(h, minh)
    rect(c, x, y, w, h, INK, fill, 0.7)


